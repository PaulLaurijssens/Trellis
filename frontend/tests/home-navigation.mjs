// Isolated UI regression for unified search and the learning sidebar.
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.MENTOR_PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.MENTOR_BROWSER_PATH?{executablePath:process.env.MENTOR_BROWSER_PATH}:{})});
try {
 const page=await browser.newPage({viewport:{width:1600,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(12000);
 await page.addInitScript(()=>localStorage.setItem('trellis.lang','en'));
 const nodes=[{id:'v',name:'Vectors',status:'learning'},{id:'a',name:'Attention',status:'queued'},{id:'r',name:'Robotics',status:'queued'}];
 await page.route('http://localhost:8000/**',async route=>{
  const path=decodeURIComponent(new URL(route.request().url()).pathname);
  if(route.request().method()==='OPTIONS'){await route.fulfill({status:204,headers:{'Access-Control-Allow-Origin':'*','Access-Control-Allow-Headers':'content-type'}});return;}
  let data;
  if(path==='/graph')data={nodes,edges:[{source:'v',target:'a',type:'PREREQUISITE_OF'}]};
  else if(path==='/levels')data={1:'First steps',2:'Foundations',3:'Practical',4:'Technical',5:'Advanced'};
  else if(path.startsWith('/memory/'))data={ui_language:'en',ambient_motion:false,learning_profile:{},concepts:[]};
  else if(path==='/journey/paul')data={active_goal:null,goals:[],recent:{concept:'Vectors',consolidated:false},review:[],sources:[]};
  else if(path==='/journey/paul/examples')data=[];
  else if(path.startsWith('/concept/'))data={...nodes.find(n=>n.name===path.slice(9)),definition:'A useful topic with connections.',mentions:[{source:'Fixture source',context:'Stored source context'}]};
  else if(path.startsWith('/chat/'))data={session_id:null,messages:[],state:{},suggestions:[]};
  else if(path==='/translations')data={texts:JSON.parse(route.request().postData()).texts};
  else throw Error('Unexpected request '+path);
  await route.fulfill({status:200,contentType:'application/json',headers:{'Access-Control-Allow-Origin':'*'},body:JSON.stringify(data)});
 });
 await page.goto('http://localhost:3000');
 const rail=page.getByRole('complementary',{name:'Your learning space'});
 await rail.getByRole('heading',{name:'Vectors',exact:true}).waitFor();
 assert.equal(await page.locator('.learning-home,.atlas-browse').count(),0);
 const search=page.locator('.cmd-row input');
 await search.click();
 await page.locator('#knowledge-navigation').waitFor();
 assert.equal(await page.locator('.cmd-item').count(),3);
 await page.getByRole('button',{name:'Clusters · 1',exact:true}).click();
 await page.locator('.cmd-item').nth(1).click();
 await page.locator('#knowledge-navigation').waitFor({state:'detached'});
 await page.locator('.cluster-start').waitFor();
 await page.locator('.scope-chip').waitFor();
 const canvas=page.locator('.living-graph > svg'), box=await canvas.boundingBox();
 await page.mouse.move(box.x+box.width-35,box.y+box.height-150);await page.mouse.down();await page.mouse.move(box.x+box.width-95,box.y+box.height-180,{steps:6});await page.mouse.up();
 assert.equal(await canvas.evaluate(el=>getComputedStyle(el).outlineStyle),'none','panning must not draw a focus box');
 await page.locator('.scope-chip').click();
 await page.locator('.cluster-start').waitFor({state:'detached'});
 await rail.getByRole('button',{name:'Another topic ↗',exact:true}).click();
 await page.locator('#knowledge-navigation').waitFor();
 await search.fill('Attention');
 assert.equal(await page.locator('.cmd-item').count(),1);
 await page.locator('.cmd-item').first().click();
 await rail.getByRole('heading',{name:'Attention',exact:true}).waitFor();
 await rail.getByRole('heading',{name:'Vectors',exact:true}).waitFor();
 assert.equal(await page.locator('#knowledge-navigation').count(),0);
 const sources=rail.locator('details').filter({hasText:'Fixture source'});
 await sources.locator('summary').click();
 assert.equal(await sources.getAttribute('open'),'');
 await search.click();
 assert.equal(await sources.getAttribute('open'),null,'search click closes the source disclosure');
 await canvas.click({position:{x:15,y:box.height-120}});
 assert.equal(await page.locator('#knowledge-navigation').count(),0,'canvas click closes search');
 await rail.getByRole('button',{name:'Another topic ↗',exact:true}).click();
 await search.fill('Vectors');await page.locator('.cmd-item').first().click();
 await rail.getByText('Current topic · last conversation',{exact:true}).waitFor();
 assert.equal(await rail.locator('.last-conversation').count(),0,'same topic must not produce duplicate resume cards');
 await rail.locator('.preview-close').click();
 await rail.locator('.last-conversation').waitFor();
 await search.click();await page.keyboard.press('Escape');
 assert.equal(await page.locator('#knowledge-navigation').count(),0);
 await page.getByRole('button',{name:'Add +',exact:true}).click();
 await page.getByRole('dialog',{name:'Add',exact:true}).waitFor();
 await canvas.click({position:{x:15,y:box.height-120}});
 assert.equal(await page.getByRole('dialog',{name:'Add',exact:true}).count(),0,'outside click closes add form');
 await search.click();await page.keyboard.press('ArrowDown');
 assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('cmd-item')),true);
 await page.keyboard.press('Escape');
 await page.screenshot({path:'/private/tmp/home-navigation-desktop.png',fullPage:true,animations:"disabled"});
 await page.setViewportSize({width:390,height:844});
 await rail.getByRole('button',{name:'Another topic ↗',exact:true}).click();
 await page.locator('#knowledge-navigation').waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'/private/tmp/home-navigation-mobile.png',fullPage:true,animations:"disabled"});
 assert.deepEqual(errors,[]);
 console.log('PASS: unified topic/cluster search, selected/recent deduplication, persistent sidebar, pointer panning without border, outside/Escape dismissal, add-form dismissal, keyboard navigation and mobile.');
}finally{await browser.close();}
